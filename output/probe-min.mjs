import { mkdir } from 'node:fs/promises';
import { appendFileSync } from 'node:fs';
const log = m => appendFileSync('output/relic-probe.log', m + '\n');
const modulePath = process.env.PLAYWRIGHT_MODULE || 'C:/Users/DevTrivi/AppData/Local/npm-cache/_npx/9833c18b2d85bc59/node_modules/playwright/index.mjs';
const { chromium } = await import('file:///' + modulePath.replace(/\\/g, '/'));
const browser = await chromium.launch({ headless:true, executablePath:process.env.CHROMIUM_PATH || 'C:/Users/DevTrivi/AppData/Local/ms-playwright/chromium-1228/chrome-win64/chrome.exe' });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await mkdir('output/night-hunters', { recursive: true });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto('http://127.0.0.1:8080/night.html', { timeout: 20000 });
await page.waitForFunction(() => !document.querySelector('#start')?.disabled, null, { timeout: 12000 }).catch(() => log('start button never enabled'));
await page.evaluate(async () => { window.nightTest = await import('/src/night.js'); });
await page.locator('#start').click();
await page.locator('[data-hunter="relic"]').first().click();
await page.waitForTimeout(500);
log('PICK ' + JSON.stringify(await page.evaluate(() => ({ kind: window.nightTest.stage.kind, name: window.nightTest.stage.player.name }))));
await page.screenshot({ path: 'output/night-hunters/relic-pick.png' });
await page.keyboard.down('a');
try { await page.waitForFunction(() => window.nightTest.stage.vista?.active, null, { timeout: 8000 }); } catch { log('no vista after walk west'); }
await page.keyboard.up('a');
await page.waitForTimeout(900);
log('RUINS ' + JSON.stringify(await page.evaluate(() => ({ x: Math.round(window.nightTest.stage.player.x), kind: window.nightTest.stage.kind, vista: !!window.nightTest.stage.vista?.active }))));
await page.screenshot({ path: 'output/night-hunters/relic-ruins.png' });
await page.keyboard.press('l');
await page.waitForTimeout(600);
await page.keyboard.press('l');
await page.waitForTimeout(1000);
log('RELAY ' + JSON.stringify(await page.evaluate(() => ({ relay: window.nightTest.stage.relic.relay, powered: window.nightTest.stage.vista.powered }))));
await page.screenshot({ path: 'output/night-hunters/relic-relay.png' });
await page.keyboard.down('d');
try { await page.waitForFunction(() => !window.nightTest.stage.vista?.active, null, { timeout: 8000 }); } catch { log('no exit after walk east'); }
await page.keyboard.up('d');
await page.waitForTimeout(600);
log('BACK ' + JSON.stringify(await page.evaluate(() => ({ x: Math.round(window.nightTest.stage.player.x), kind: window.nightTest.stage.kind }))));
log('ERR ' + JSON.stringify(errors));
await browser.close();
log('DONE');